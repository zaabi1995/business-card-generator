/**
 * Emit the Tailwind utilities the site uses and neither shipped stylesheet has.
 *
 * cardify.om loads two Tailwind builds, assets/techwind/css/tailwind.min.css
 * and assets/flowbite/app.css. Both were generated on 16 April 2026 and neither
 * has been rebuilt since, while pages kept adding classes. Anything added after
 * that date renders as nothing unless it happened to already be in one of them.
 * Measured on production: text-start left the /get-started hero centred at
 * desktop, rounded-3xl left the demo card square, scroll-mt-20 dropped anchor
 * jumps under the sticky header, tabular-nums did nothing on nine analytics
 * tables, and bg-teal-100 and bg-red-100 left two feature icons with no
 * background at all.
 *
 * Rather than replace either build, which would put a thousand dormant
 * selectors live at once, this writes only the difference. Existing rules are
 * untouched, so nothing that renders today can change.
 *
 * Usage: node scripts/build-css-supplement.mjs
 *   1. tailwindcss builds every utility the content globs actually use
 *   2. rules already defined by a shipped stylesheet are dropped
 *   3. the rest lands in assets/css/cardify-tailwind-supplement.css
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

/**
 * Every stylesheet the pages actually link, in load order. Comparing against
 * only the two Tailwind builds was not enough: cardify-components.css and
 * cardify-brand-2026.css define utilities too, and a supplement built without
 * them re-declared 876 rules that already render.
 */
const SHIPPED = [
  'assets/techwind/css/tailwind.min.css',
  'assets/flowbite/app.css',
  'assets/vendor/flag-icons/css/flag-icons.min.css',
  'assets/css/cardify-tokens.css',
  'assets/css/cardify-components.css',
  'assets/css/cardify-overrides.css',
  'assets/css/cardify-brand-2026.css',
  'assets/css/cardify-hero-card.css',
];
const OUT = 'assets/css/cardify-tailwind-supplement.css';

const tmp = join(mkdtempSync(join(tmpdir(), 'cardify-css-')), 'full.css');
execFileSync('npx', ['tailwindcss', '-i', 'assets/techwind/input.css', '-o', tmp, '--minify'],
  { stdio: ['ignore', 'ignore', 'inherit'] });

const full = readFileSync(tmp, 'utf8');
const shipped = SHIPPED.map(f => readFileSync(f, 'utf8')).join('\n');

/** Split a stylesheet into top-level blocks, respecting nesting. */
function blocks(css) {
  const out = [];
  let depth = 0, start = 0;
  for (let i = 0; i < css.length; i++) {
    const c = css[i];
    if (c === '{') { if (depth === 0) out.push({ prelude: css.slice(start, i) }); depth++; }
    else if (c === '}') {
      depth--;
      if (depth === 0) { out[out.length - 1].body = css.slice(css.indexOf('{', start) + 1, i); start = i + 1; }
    }
  }
  return out.filter(b => b.body !== undefined);
}

/**
 * Every class name the shipped sheets mention anywhere, at any breakpoint.
 *
 * Class NAME, not full selector: if `.rounded-3xl` is defined at all, this
 * build has nothing to add for it, and re-emitting it at a different specificity
 * would change what renders today. The comparison is deliberately conservative,
 * so the supplement can only ever add a class nothing else styles.
 */
const known = new Set();
for (const m of shipped.matchAll(/\.((?:[A-Za-z0-9_-]|\\.)+)/g)) {
  known.add(m[1].replace(/\\/g, ''));
}

function classesIn(selector) {
  return [...selector.matchAll(/\.((?:[A-Za-z0-9_-]|\\.)+)/g)].map(m => m[1].replace(/\\/g, ''));
}

function keepPrelude(prelude, _media) {
  const kept = prelude.split(',')
    .map(s => s.trim())
    .filter(s => {
      if (!s.startsWith('.')) return false;
      const names = classesIn(s);
      return names.length > 0 && names.every(n => !known.has(n));
    });
  return kept.length ? kept.join(',') : null;
}

let outCss = '';
for (const b of blocks(full)) {
  const p = b.prelude.trim();
  if (p.startsWith('@media')) {
    let inner = '';
    for (const r of blocks(b.body)) {
      const keep = keepPrelude(r.prelude, p);
      if (keep) inner += keep + '{' + r.body + '}';
    }
    if (inner) outCss += p + '{' + inner + '}';
  } else if (p.startsWith('@')) {
    // keyframes, layer directives, font-face: only carried when referenced by a
    // kept rule, which utilities here never are. Skipped on purpose.
    continue;
  } else {
    const keep = keepPrelude(p, '');
    if (keep) outCss += keep + '{' + b.body + '}';
  }
}

const CHECK = process.argv.includes('--check');

const header = `/* Generated by scripts/build-css-supplement.mjs. Do not edit by hand.
 * The Tailwind utilities this site uses that neither shipped build contains,
 * because both were last generated on 16 April 2026. Regenerate after adding
 * classes: node scripts/build-css-supplement.mjs
 */\n`;
const content = header + outCss + '\n';
if (CHECK) {
  // --check regenerates and compares. It is what tests/php/tailwind_supplement_test.php
  // runs: a class added to a page after the last build would otherwise be dead
  // and nothing would say so.
  let current = '';
  try { current = readFileSync(OUT, 'utf8'); } catch { current = ''; }
  if (current === content) {
    console.log('supplement up to date');
    process.exit(0);
  }
  const missing = [...new Set(
    [...outCss.matchAll(/\.((?:[A-Za-z0-9_-]|\\.)+)\s*\{/g)].map(m => m[1].replace(/\\/g, ''))
  )].filter(c => !current.includes('.' + c.replace(/([^A-Za-z0-9_-])/g, '\\$1') + '{'));
  console.error('supplement is stale. Run: npm run build:css');
  if (missing.length) console.error('classes with no style anywhere: ' + missing.slice(0, 20).join(', '));
  process.exit(1);
}
writeFileSync(OUT, content);
console.log(`${OUT}: ${outCss.length} bytes`);
